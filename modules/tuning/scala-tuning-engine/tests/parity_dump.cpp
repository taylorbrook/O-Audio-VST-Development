/*
    One "case<TAB>value" line per scenario, using only API common to the module
    and the fork copies. parity_gate.py compares the output across trees.
*/

#include "TuningEngine.h"
#include "ScaleGenerator.h"
#include "EmbeddedTunings.h"
#include "TuningExporter.h"
#include <cstdio>

static juce::String nums(const std::vector<double>& v)
{
    juce::String s;
    for (auto d : v) s += juce::String(d, 6) + " ";
    return s;
}

static void emit(const char* name, const juce::String& value)
{
    std::printf("%s\t%s\n", name, value.toRawUTF8());
}

static bool loadFile(TuningEngine& e, const juce::String& text, const char* ext)
{
    auto f = juce::File::createTempFile(ext);
    f.replaceWithText(text);
    const bool ok = juce::String(ext) == ".scl" ? e.loadScalaFile(f) : e.loadKBMFile(f);
    f.deleteFile();
    return ok;
}

static void scl(const char* name, const juce::String& text)
{
    TuningEngine e;
    const bool ok = loadFile(e, text, ".scl");
    emit(name, ok ? "ok " + nums(e.getIntervals()) : juce::String("rejected"));
}

static std::vector<double> twelve() { return { 0, 100, 200, 300, 400, 500, 600, 700, 800, 900, 1000, 1100, 1200 }; }

static juce::String kbmText(int size, int middle, int ref, double hz, int oct, const juce::String& map)
{
    return juce::String(size) + "\n0\n127\n" + juce::String(middle) + "\n" + juce::String(ref) + "\n"
         + juce::String(hz, 6) + "\n" + juce::String(oct) + "\n" + map;
}

static juce::String idMap(int n)
{
    juce::String s;
    for (int i = 0; i < n; ++i) s += juce::String(i) + "\n";
    return s;
}

static juce::String table(TuningEngine& e)
{
    juce::String s;
    for (int n = 0; n < 128; ++n) s += juce::String(e.getFrequency(n), 6) + " ";
    return s;
}

static void kbmCase(const char* name, const juce::String& text)
{
    TuningEngine e;
    e.setCustomIntervals(twelve(), "t");
    e.setMode(TuningEngine::Mode::Scala);
    const bool ok = loadFile(e, text, ".kbm");
    emit(name, ok ? "ok a4=" + juce::String(e.getMasterTune(), 3) + " " + table(e) : juce::String("rejected"));
}

static juce::String stableHtml(const TuningEngine& e)
{
    // Drop the generated-on line, which carries the clock.
    juce::StringArray lines;
    lines.addLines(TuningExporter::toHTML(e));
    juce::StringArray kept;
    for (const auto& l : lines)
        if (! l.contains("Generated by") && ! l.contains("metadata-value\">20"))
            kept.add(l);
    return juce::String(kept.joinIntoString("\n").hashCode64());
}

int main(int argc, char**)
{
    // Any argument: skip the cases that hang a tree without CR-08/CR-09 (the baseline).
    const bool skipHanging = argc > 1;

    // ── .scl parser ──
    scl("scl.negcents", "neg\n2\n-50.0\n1200.0\n");
    scl("scl.blankdesc", "! c\n\n2\n3/2\n2/1\n");
    scl("scl.pitchcomment", "n\n2\n3/2 fifth\n1200.0 octave\n");
    scl("scl.malformed", "n\n3\n100.0\nabc\n1200.0\n");
    scl("scl.short", "n\n3\n100.0\n1200.0\n");
    scl("scl.count0", "n\n0\n1200.0\n");
    scl("scl.count5000", "n\n5000\n1200.0\n");
    scl("scl.tworatios", "n\n2\n3/2/5\n1200.0\n");
    scl("scl.infratio", "n\n2\n" + juce::String::repeatedString("9", 400) + "/"
                                  + juce::String::repeatedString("9", 400) + "\n1200.0\n");
    scl("scl.valid", "n\n4\n9/8\n5/4\n386.31\n2/1\n");

    // ── .kbm ──
    kbmCase("kbm.ref_c", kbmText(12, 60, 60, 261.63, 12, idMap(12)));
    kbmCase("kbm.ref_a4", kbmText(12, 60, 69, 440.0, 12, idMap(12)));
    if (! skipHanging) // without CR-08 this allocates 2 billion map entries
        kbmCase("kbm.map_huge", kbmText(2000000000, 60, 60, 261.63, 12, idMap(12)));
    kbmCase("kbm.octdeg7", kbmText(12, 60, 60, 261.63, 7, idMap(12)));
    kbmCase("kbm.degree_wrap", kbmText(12, 60, 60, 261.63, 12, "0\n12\n14\n3\n4\n5\n6\n7\n8\n9\n10\n11\n"));
    {
        TuningEngine e;
        e.setCustomIntervals(twelve(), "t");
        e.setMode(TuningEngine::Mode::Scala);
        loadFile(e, kbmText(12, 60, 60, 261.63, 12, idMap(12)), ".kbm");
        juce::StringArray lines;
        lines.addLines(e.generateKBMFileContent());
        lines.removeEmptyStrings();
        juce::StringArray data;
        for (const auto& l : lines) if (! l.startsWith("!")) data.add(l);
        emit("kbm.save_reference", data[5]);
    }

    // ── edits ──
    {
        TuningEngine e;
        e.setCustomIntervals({ 0, 109, 218, 327, 436, 545, 655, 764, 873, 982, 1091, 1200 }, "11");
        e.setSingleInterval(3, 333.0);
        emit("edit.eleven", nums(e.getIntervals()));
    }

    // ── generator ──
    emit("gen.rank2_order", nums(ScaleGenerator::generateRank2(700.0, 50.0, 5)));
    if (! skipHanging)
    {
        emit("gen.rank2_huge", nums(ScaleGenerator::generateRank2(1e13, 1e13, 7)));
        emit("gen.rank2_nonfinite", nums(ScaleGenerator::generateRank2(std::nan(""), std::numeric_limits<double>::infinity(), 7)));
    }
    emit("dflt.gen_rank2", nums(ScaleGenerator::generateRank2(696.578, 1200.0, 12)));
    emit("dflt.gen_edo19", nums(ScaleGenerator::generateEDO(19)));
    emit("dflt.gen_bp", nums(ScaleGenerator::generateEDO(13, 1902.0)));
    emit("dflt.gen_harm", nums(ScaleGenerator::generateHarmonicSeries(8, 16)));

    // ── embedded ──
    if (const auto* p = EmbeddedTunings::getTuningById("just/partch43"))
        emit("emb.partch43", nums(p->intervals));
    {
        juce::String s;
        for (const auto& t : EmbeddedTunings::getAllTunings())
            if (juce::String(t.id) != "just/partch43")
                s += juce::String(t.id) + ":" + nums(t.intervals) + juce::String(t.period, 3) + " ";
        emit("dflt.emb_others", juce::String(s.hashCode64()));
    }

    // ── exporter ──
    emit("exp.et_zero_degrees", juce::String(TuningExporter::calculateETDeviation(100.0, 1, 0, 1200.0), 3));
    emit("exp.svg_12tet", juce::String(TuningExporter::generatePitchCircleSVG(twelve(), 1200.0, "s").hashCode64()));
    {
        TuningEngine e;
        e.setCustomIntervals({ 0, 78, 156, 234, 312, 390, 468, 546, 624, 702 }, "sub");
        e.setMode(TuningEngine::Mode::Scala);
        emit("exp.html_suboctave", stableHtml(e));
    }
    {
        TuningEngine e;
        loadFile(e, "<script>x</script>\n1\n1200.0\n", ".scl");
        emit("exp.html_escape", TuningExporter::toHTML(e).contains("<script>x") ? "raw" : "escaped");
    }

    // ── paths the fixes must NOT move (baseline only) ──
    {
        TuningEngine e;
        e.setMode(TuningEngine::Mode::TwelveTET);
        emit("dflt.tbl_12tet", table(e));
        e.setMasterTune(442.0);
        emit("dflt.tbl_442", table(e));
        e.setOctaveStretch(1.02f);
        emit("dflt.tbl_stretch", table(e));
    }
    {
        TuningEngine e;
        e.setCustomIntervals(ScaleGenerator::generateEDO(19), "19");
        e.setMode(TuningEngine::Mode::Scala);
        emit("dflt.tbl_19edo", table(e));
        e.setTonicNote(3);
        emit("dflt.tbl_19edo_tonic3", table(e));
    }
    for (int p = 0; p < static_cast<int>(TuningEngine::BuiltInPreset::Custom); ++p)
    {
        TuningEngine e;
        e.setBuiltInPreset(static_cast<TuningEngine::BuiltInPreset>(p));
        const auto key = "dflt.tbl_preset" + juce::String(p);
        emit(key.toRawUTF8(), table(e));
    }
    return 0;
}
