/** A held copy of every MipRing level over a region, read in snapshot coordinates:
    position b (level-0 samples, double) is absolute level-0 time origin + b, where
    origin is the first captured sample. Each level keeps 8 * 2^l + 1 samples of
    pre-roll before b = 0 and 8 after the newest, so a 16-tap read anywhere in
    [0, length) never clamps; positions outside are clamped to the stored span. */
template <int L = 3>
class MipSnapshot
{
public:
    using Ring = MipRing<L>;
    static constexpr int kNumLevels = L + 1;

    /** Allocates for regions up to maxLengthSamples (call off the audio thread). */
    void prepare (int maxLengthSamples)
    {
        bank = &sincBank();
        maxLength = std::max (0, maxLengthSamples);
        for (int l = 0; l < kNumLevels; ++l)
            for (auto& d : data[(size_t) l])
                d.assign ((size_t) storageFor (l, maxLength), 0.0f);
        clear();
    }

    void clear() noexcept
    {
        for (auto& lv : data)
            for (auto& d : lv)
                std::fill (d.begin(), d.end(), 0.0f);
        length = 0;
        origin = 0;
        start.fill (0);
        stored.fill (0);
    }

    /** Captures `len` level-0 samples whose newest is endDelay + 1 samples behind the
        ring's head (absolute times [W - endDelay - len, W - endDelay), W = write count),
        with every level's matching span plus the kernel pre/post-roll. endDelay must be
        >= Ring::margin (L) so every level is settled up to the captured end. */
    void captureFrom (const Ring& ring, int endDelay, int len) noexcept
    {
        len = std::clamp (len, 0, maxLength);
        const std::int64_t end = ring.getWriteCount() - endDelay;   // one past the newest captured sample
        origin = end - len;
        length = len;
        for (int l = 0; l < kNumLevels; ++l)
        {
            const std::int64_t first = Ring::levelPos (l, origin, 0.0).index - blr::kTapsBack - 1;
            const std::int64_t last  = Ring::levelPos (l, end, 0.0).index + blr::kTapsAhead;
            const int n = static_cast<int> (std::min<std::int64_t> (last - first + 1, (std::int64_t) data[(size_t) l][0].size()));
            start[(size_t) l] = first;
            stored[(size_t) l] = n;
            for (int ch = 0; ch < 2; ++ch)
                ring.copyLevel (l, ch, first, n, data[(size_t) l][(size_t) ch].data());
        }
    }

    int getLength() const noexcept { return length; }
    std::int64_t getOrigin() const noexcept { return origin; }

    float read (int level, int ch, double pos, int set) const noexcept
    {
        float k[blr::kTaps];
        const int s = locateStart (level, pos, set, k);
        return blr::dot16 (data[(size_t) level][(size_t) ch].data() + s, k);
    }

    void readStereo (int level, double pos, int set, float& outL, float& outR) const noexcept
    {
        float k[blr::kTaps];
        const int s = locateStart (level, pos, set, k);
        outL = blr::dot16 (data[(size_t) level][0].data() + s, k);
        outR = blr::dot16 (data[(size_t) level][1].data() + s, k);
    }

    float readMono (int level, double pos, int set) const noexcept
    {
        float k[blr::kTaps];
        const int s = locateStart (level, pos, set, k);
        return 0.5f * blr::dot16Sum (data[(size_t) level][0].data() + s, data[(size_t) level][1].data() + s, k);
    }

private:
    static int storageFor (int l, int len) noexcept
    {
        return (len >> l) + 2 * blr::kTaps + 4;
    }

    int locateStart (int level, double pos, int set, float* k) const noexcept
    {
        const double bI = std::floor (pos);
        const Pos p = Ring::levelPos (level, origin + static_cast<std::int64_t> (bI), pos - bI);
        bank->kernel (set, p.frac, k);
        const std::int64_t s = p.index - blr::kTapsBack - start[(size_t) level];
        const std::int64_t hi = std::max<std::int64_t> (0, stored[(size_t) level] - blr::kTaps);
        return static_cast<int> (std::clamp<std::int64_t> (s, 0, hi));
    }

    using Pos = typename Ring::Pos;

    const SincBank* bank = nullptr;
    std::array<std::array<std::vector<float>, 2>, kNumLevels> data;
    std::array<std::int64_t, kNumLevels> start {};
    std::array<int, kNumLevels> stored {};
    std::int64_t origin = 0;
    int length = 0;
    int maxLength = 0;
};

