/** 8 sets x 257 phases x 16 taps of unity-DC Kaiser-windowed sinc. Row p of a set
    is the kernel for a read at i0 + p/256, taps i0-7 .. i0+8. */
class SincBank
{
public:
    static constexpr int kTaps    = blr::kTaps;
    static constexpr int kPhases  = blr::kPhases;
    static constexpr int kNumSets = blr::kNumSets;

    SincBank()
    {
        for (int s = 0; s < kNumSets; ++s)
        {
            const double fc   = blr::kSincSets[s].fc;
            const double beta = blr::kSincSets[s].beta;
            const double i0b  = blr::besselI0 (beta);
            for (int p = 0; p <= kPhases; ++p)
            {
                const double fr = static_cast<double> (p) / kPhases;
                double h[kTaps];
                double sum = 0.0;
                for (int k = 0; k < kTaps; ++k)
                {
                    const double t = static_cast<double> (k - blr::kTapsBack) - fr;
                    const double u = 2.0 * t / kTaps;
                    const double w = blr::besselI0 (beta * std::sqrt (std::max (0.0, 1.0 - u * u))) / i0b;
                    const double x = 2.0 * fc * t;
                    const double sinc = (x == 0.0) ? 1.0 : std::sin (kPi * x) / (kPi * x);
                    h[k] = 2.0 * fc * sinc * w;
                    sum += h[k];
                }
                float* dst = rows.data() + index (s, p);
                for (int k = 0; k < kTaps; ++k)
                    dst[k] = static_cast<float> (h[k] / sum);
            }
        }
    }

    /** Stored row (float) of set s, phase p in [0, kPhases]. */
    const float* row (int set, int phase) const noexcept { return rows.data() + index (set, phase); }

    /** Kernel for fractional position fr in [0, 1): rows lerped. */
    void kernel (int set, double fr, float* out) const noexcept
    {
        const double x = fr * kPhases;
        int ip = static_cast<int> (x);
        ip = std::clamp (ip, 0, kPhases - 1);
        const float u = static_cast<float> (x - static_cast<double> (ip));
        const float* a = row (set, ip);
        const float* b = a + kTaps;
        for (int k = 0; k < kTaps; ++k)
            out[k] = a[k] + u * (b[k] - a[k]);
    }

    /** Set for a residual rate r' (level samples per output sample): S0 for r' <= 1,
        else the first set whose upper edge is >= r', S7 above 2. Branch-free. */
    static int setFor (double rPrime) noexcept
    {
        int s = 0;
        for (int k = 0; k < kNumSets - 1; ++k)
            s += (rPrime > blr::kSincSets[k].edge) ? 1 : 0;
        return s;
    }

private:
    static constexpr double kPi = 3.14159265358979323846;
    static constexpr std::size_t index (int set, int phase) noexcept
    {
        return (static_cast<std::size_t> (set) * (kPhases + 1) + static_cast<std::size_t> (phase)) * kTaps;
    }

    std::array<float, static_cast<std::size_t> (kNumSets) * (kPhases + 1) * kTaps> rows {};
};

/** The shared bank (128 KB, static storage). Built on the first call: make that call
    off the audio thread (MipRing::prepare / MipSnapshot::prepare do). */
inline const SincBank& sincBank()
{
    static const SincBank bank;
    return bank;
}

/** Octave level for a grain's base rate: clamp (floor (log2 rate), 0, maxLevel). */
inline int latchLevel (double rate, int maxLevel = 3) noexcept
{
    if (! (rate >= 2.0)) return 0;                      // also catches NaN
    return std::min (maxLevel, std::ilogb (rate));      // exact floor (log2) for normal doubles
}

