/*
  ==============================================================================

    grain-engine - BandlimitedReader (1.1.0)

    A band-limited grain reader: pitched-up grains read without aliasing.

      MipRing<L>   stereo ring of level 0 (the raw input) plus L octave levels,
                   each built on the WRITE path by a causal 127-tap Kaiser
                   half-band and a 2:1 decimation (level l runs at fs / 2^l).
      SincBank     16-tap Kaiser-windowed sinc kernels: 8 cutoff sets x 257
                   fractional phases, each row normalised to sum exactly 1 in
                   double before it is stored as float (unity DC per phase;
                   phases between rows are lerped, a lerp of two unity rows is
                   unity).
      MipSnapshot  a held copy of every level over a region of the ring, for
                   freeze-style playback in snapshot coordinates.

    How a grain reads:
      1. At spawn, latch the octave level from its base rate:
             level = latchLevel (rate) = clamp (floor (log2 rate), 0, L)
      2. Per sample, the residual rate on that level r' = rate * mod / 2^level
         picks the sinc set (setFor (r')): the first set whose upper edge is
         >= r' (S0 for r' <= 1, S1..S6 up to 2^(k/6), S7 best effort above 2).
         The residual alone decides; a Doppler swing moves between sets, never
         between levels, so nothing switches source inside a grain.
      3. read / readStereo / readMono with the delay from the write head in
         LEVEL-0 samples (double). Level l is time-aligned with level 0:

             p_l = (p_0 + D(l) - (2^l - 1)) / 2^l,   D(l) = 63 (2^l - 1)

         The integer and fractional parts are split before any division, so
         the precision of a read depends on the delay only, never on how long
         the ring has been running.

    Read guard: a level-l read needs level samples up to p_l + 8, which exist
    only margin(l) = D(l) + 8 * 2^l + 1 samples behind the head (9 / 80 / 222 /
    506). read*() clamps the delay to margin(level) itself, so a caller that
    over-runs the head (e.g. a Doppler-modulated grain spawned at the floor)
    reads the newest settled audio instead of wrapping to the oldest.

    Real-time contract: prepare() allocates; everything else (clear, push,
    read*, MipSnapshot::captureFrom / read*) is allocation-, lock- and
    log-free. sincBank() builds its table on first call (a function-local
    static): call it once off the audio thread (prepare() does).

    Block-size invariance: push() runs the whole cascade per input sample, and
    level l takes its output on odd parent indices of an absolute counter, so
    the stored levels are a pure function of the input sequence.

    Plain C++20, no JUCE.

  ==============================================================================
*/
