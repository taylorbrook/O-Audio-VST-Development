/** Stereo ring + L half-band octave levels, mirrored for contiguous 16-tap reads. */
template <int L = 3>
class MipRing
{
public:
    static_assert (L >= 0 && L <= 6, "MipRing: 0..6 octave levels");
    static constexpr int kLevels = L;
    static constexpr int kNumLevels = L + 1;

    /** Accumulated half-band delay of level l, in level-0 samples: 63 (2^l - 1). */
    static constexpr int delayOf (int level) noexcept { return blr::kHbDelay * ((1 << level) - 1); }

    /** Smallest delay (level-0 samples behind the head) a level-l read can take. */
    static constexpr int margin (int level) noexcept { return delayOf (level) + blr::kTapsAhead * (1 << level) + 1; }

    /** Fractional level-l index of absolute level-0 time p0 (diagnostics / tests). */
    static constexpr double levelIndex (int level, double p0) noexcept
    {
        return (p0 + delayOf (level) - ((1 << level) - 1)) / static_cast<double> (1 << level);
    }

    /** A level position: integer level index + fraction in [0, 1). */
    struct Pos { std::int64_t index; double frac; };

    /** Level-l position of absolute level-0 time t + phi (phi in [0, 1)), exactly. */
    static Pos levelPos (int level, std::int64_t t, double phi) noexcept
    {
        const std::int64_t q = t + delayOf (level) - ((1 << level) - 1);
        const std::int64_t mask = (std::int64_t (1) << level) - 1;
        return { q >> level, (static_cast<double> (q & mask) + phi) / static_cast<double> (1 << level) };
    }

    /** Allocates every level (call off the audio thread). capacitySamples = level-0 length. */
    void prepare (int capacitySamples)
    {
        bank = &sincBank();
        for (int l = 0; l < kNumLevels; ++l)
        {
            cap[(size_t) l] = std::max (blr::kTaps * 2, (capacitySamples >> l) + 64);
            for (int ch = 0; ch < 2; ++ch)
                data[(size_t) l][(size_t) ch].assign ((size_t) (cap[(size_t) l] + blr::kTaps), 0.0f);
        }
        clear();
    }

    /** Zeroes every level and the cascade state; no allocation (CR-02). */
    void clear() noexcept
    {
        for (int l = 0; l < kNumLevels; ++l)
        {
            for (auto& d : data[(size_t) l])
                std::fill (d.begin(), d.end(), 0.0f);
            count[(size_t) l] = 0;
            widx[(size_t) l] = 0;
        }
        for (auto& lv : hist)
            for (auto& h : lv)
                h.fill (0.0f);
    }

    /** One stereo input sample. Runs the cascade: level l+1 takes a sample whenever
        level l's absolute index is odd. */
    void push (float inL, float inR) noexcept
    {
        float v[2] = { inL, inR };
        for (int l = 0; l < kNumLevels; ++l)
        {
            const std::int64_t n = count[(size_t) l];
            store (l, v);
            if (l == L) break;

            const int h = static_cast<int> (n & (blr::kHbHistory - 1));
            for (int ch = 0; ch < 2; ++ch)
            {
                auto& hb = hist[(size_t) l][(size_t) ch];
                hb[(size_t) h] = v[ch];
                hb[(size_t) (h + blr::kHbHistory)] = v[ch];
            }
            if ((n & 1) == 0) break;          // child sample on odd parent indices only

            for (int ch = 0; ch < 2; ++ch)
                v[ch] = halfband (hist[(size_t) l][(size_t) ch].data(), h);
        }
    }

    // ── reads ───────────────────────────────────────────────────────────────
    /** One channel at `delay` level-0 samples behind the head (clamped to margin). */
    float read (int level, int ch, double delay, int set) const noexcept
    {
        float k[blr::kTaps];
        const float* src = locate (level, ch, delay, set, k);
        return blr::dot16 (src, k);
    }

    void readStereo (int level, double delay, int set, float& outL, float& outR) const noexcept
    {
        float k[blr::kTaps];
        const std::int64_t s = locateStart (level, delay, set, k);
        outL = blr::dot16 (data[(size_t) level][0].data() + s, k);
        outR = blr::dot16 (data[(size_t) level][1].data() + s, k);
    }

    /** (L + R) / 2 through one 16-MAC convolution (the reader is linear). */
    float readMono (int level, double delay, int set) const noexcept
    {
        float k[blr::kTaps];
        const std::int64_t s = locateStart (level, delay, set, k);
        return 0.5f * blr::dot16Sum (data[(size_t) level][0].data() + s, data[(size_t) level][1].data() + s, k);
    }

    // ── state ───────────────────────────────────────────────────────────────
    /** Level-0 samples pushed since prepare / clear (absolute write counter). */
    std::int64_t getWriteCount() const noexcept { return count[0]; }
    std::int64_t getLevelCount (int level) const noexcept { return count[(size_t) level]; }
    int getCapacity (int level = 0) const noexcept { return cap[(size_t) level]; }

    /** Level sample at absolute level index j (must be inside the ring). */
    float levelSample (int level, int ch, std::int64_t j) const noexcept
    {
        return data[(size_t) level][(size_t) ch][(size_t) wrap (level, j)];
    }

    /** Copies level samples [first, first + n) of channel ch into dst (n <= capacity). */
    void copyLevel (int level, int ch, std::int64_t first, int n, float* dst) const noexcept
    {
        const int c = cap[(size_t) level];
        const int s = static_cast<int> (wrap (level, first));
        const int run = std::min (n, c - s);
        const float* src = data[(size_t) level][(size_t) ch].data();
        std::memcpy (dst, src + s, sizeof (float) * (size_t) run);
        if (n > run)
            std::memcpy (dst + run, src, sizeof (float) * (size_t) (n - run));
    }

private:
    std::int64_t wrap (int level, std::int64_t j) const noexcept
    {
        const std::int64_t c = cap[(size_t) level];
        std::int64_t m = j % c;
        return m < 0 ? m + c : m;
    }

    void store (int l, const float* v) noexcept
    {
        const int w = widx[(size_t) l];
        for (int ch = 0; ch < 2; ++ch)
        {
            auto& d = data[(size_t) l][(size_t) ch];
            d[(size_t) w] = v[ch];
            if (w < blr::kTaps)
                d[(size_t) (cap[(size_t) l] + w)] = v[ch];   // mirrored guard
        }
        widx[(size_t) l] = (w + 1 == cap[(size_t) l]) ? 0 : w + 1;
        ++count[(size_t) l];
    }

    // Causal half-band: y = sum_k hb[k] x[n - k], n = newest parent index (odd),
    // folded on the centre tap k = 63. x[n - k] lives at hist[h + 128 - k].
    static float halfband (const float* x, int h) noexcept
    {
        const float* c = x + h + blr::kHistCentreOffset;
        double acc = 0.5 * static_cast<double> (c[0]);
        for (int m = 0; m < 32; ++m)
            acc += blr::kHalfbandOdd[m] * (static_cast<double> (c[-(2 * m + 1)]) + static_cast<double> (c[2 * m + 1]));
        return static_cast<float> (acc);
    }

    // Splits delay into (absolute level-0 time, fraction), maps it to the level and
    // fills the kernel; returns the mirrored-ring start of the 16 taps.
    std::int64_t locateStart (int level, double delay, int set, float* k) const noexcept
    {
        delay = std::max (delay, static_cast<double> (margin (level)));
        const double dI = std::floor (delay);
        const double df = delay - dI;
        std::int64_t t = count[0] - static_cast<std::int64_t> (dI);
        double phi = 0.0;
        if (df > 0.0) { t -= 1; phi = 1.0 - df; }
        const Pos p = levelPos (level, t, phi);
        bank->kernel (set, p.frac, k);
        return wrap (level, p.index - blr::kTapsBack);
    }

    const float* locate (int level, int ch, double delay, int set, float* k) const noexcept
    {
        return data[(size_t) level][(size_t) ch].data() + locateStart (level, delay, set, k);
    }

    const SincBank* bank = nullptr;
    std::array<std::array<std::vector<float>, 2>, kNumLevels> data;
    std::array<int, kNumLevels> cap {};
    std::array<int, kNumLevels> widx {};
    std::array<std::int64_t, kNumLevels> count {};
    std::array<std::array<std::array<float, 2 * blr::kHbHistory>, 2>, (L > 0 ? L : 1)> hist {};
};

