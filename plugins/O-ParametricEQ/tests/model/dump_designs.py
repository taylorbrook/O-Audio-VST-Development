"""Writes the designs golden to stdout (PLAN-2.1 T2). Deterministic: a fixed, enumerated
settings list, no RNG.

    python3 plugins/O-ParametricEQ/tests/model/dump_designs.py > plugins/O-ParametricEQ/tests/golden/designs.tsv

Loop order (outer to inner): fs, type (eq::Type order), slope index, fc, q, gain, section.
Lines that start with '#' are comments. Unused cells are '-'. hasSvf / hasOnePole are 1 / 0.
"""
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import eqmodel as m  # noqa: E402

FS = (44100.0, 48000.0, 88200.0, 96000.0, 192000.0)
SLOPE_INDICES = (0, 1, 2, 3, 5, 7)
FCS = (10.0, 20.0, 100.0, 999.99988, 5000.0, 12000.0, 18000.0, 20900.0, 21500.0, 25000.0, 30000.0)
QS = (0.025, 0.3, 0.70710678, 0.99999976, 1.41, 4.0, 40.0)
GAINS = (-60.0, -30.0, -6.0, 0.0, 3.0, 18.0, 60.0)
NO_GAIN = (0.0,)

COLUMNS = ('fs', 'type', 'slope', 'fc', 'q', 'gain', 'sec', 'cls', 'hasSvf', 'hasOnePole',
           'g', 'k', 'mL', 'mB', 'mH', 'G', 'cL', 'cH')
SVF_KEYS = ('g', 'k', 'mL', 'mB', 'mH')
OP_KEYS = ('G', 'cL', 'cH')


def num(x, where):
    x = float(x)
    if not math.isfinite(x):
        sys.stderr.write('dump_designs: non-finite value at %s\n' % (where,))
        sys.exit(2)
    return '%.17g' % (x + 0.0)          # + 0.0 turns a negative zero into 0


def main():
    out = sys.stdout
    if hasattr(out, 'reconfigure'):
        out.reconfigure(newline='\n')   # never translate line endings
    w = out.write
    w('# GENERATED by tests/model/dump_designs.py; do not edit\n')
    w('# ' + '\t'.join(COLUMNS) + '\n')
    rows = 0
    for fs in FS:
        for t in m.TYPES:
            slope_inert = t not in m.SLOPE_TYPES
            gains = GAINS if t in m.GAIN_TYPES else NO_GAIN
            for si in SLOPE_INDICES:
                if slope_inert and si != 1:
                    continue
                for fc in FCS:
                    for q in QS:
                        for gain in gains:
                            where = 'fs %g %s slope %d fc %g q %g gain %g' % (fs, t, si, fc, q, gain)
                            secs = m.design_band(t, fc, gain, q, si, fs)
                            head = [num(fs, where), t, '%d' % si, num(fc, where), num(q, where),
                                    num(gain, where)]
                            for i, s in enumerate(secs):
                                cells = head + ['%d' % i, s['cls'],
                                                '1' if s['hasSvf'] else '0',
                                                '1' if s['hasOnePole'] else '0']
                                for key in SVF_KEYS:
                                    cells.append(num(s[key], where) if s['hasSvf'] else '-')
                                for key in OP_KEYS:
                                    cells.append(num(s[key], where) if s['hasOnePole'] else '-')
                                w('\t'.join(cells) + '\n')
                                rows += 1
    out.flush()
    sys.stderr.write('dump_designs: %d rows\n' % rows)


if __name__ == '__main__':
    main()
