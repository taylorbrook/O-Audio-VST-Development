"""Writes the polished-designs golden to stdout (PLAN-2.1b T2). Deterministic: the
dump_designs.py settings list restricted to Bell, Low Shelf, High Shelf and Tilt at
44.1 / 48 / 96 kHz, no RNG.

    python3 plugins/O-ParametricEQ/tests/model/dump_polish.py > plugins/O-ParametricEQ/tests/golden/designs-polished.tsv

Loop order (outer to inner): fs, type (eq::Type order), slope index, fc, q, gain, section.
Columns are those of designs.tsv plus `weight` (the accept weight of the section's polish;
0 for a first-order section and wherever the seed is kept).
"""
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import eqmodel as m  # noqa: E402
import polish_model as pm  # noqa: E402
from dump_designs import FCS, GAINS, QS, SLOPE_INDICES, COLUMNS, SVF_KEYS, OP_KEYS  # noqa: E402

FS = (44100.0, 48000.0, 96000.0)
TYPES = ('bell', 'lowShelf', 'highShelf', 'tilt')


def num(x, where):
    x = float(x)
    if not math.isfinite(x):
        sys.stderr.write('dump_polish: non-finite value at %s\n' % (where,))
        sys.exit(2)
    return '%.17g' % (x + 0.0)          # + 0.0 turns a negative zero into 0


def main():
    out = sys.stdout
    if hasattr(out, 'reconfigure'):
        out.reconfigure(newline='\n')   # never translate line endings
    w = out.write
    w('# GENERATED by tests/model/dump_polish.py; do not edit\n')
    w('# ' + '\t'.join(COLUMNS + ('weight',)) + '\n')
    rows = 0
    for fs in FS:
        for t in m.TYPES:
            if t not in TYPES:
                continue
            slope_inert = t not in m.SLOPE_TYPES
            for si in SLOPE_INDICES:
                if slope_inert and si != 1:
                    continue
                for fc in FCS:
                    for q in QS:
                        for gain in GAINS:
                            where = 'fs %g %s slope %d fc %g q %g gain %g' % (fs, t, si, fc, q, gain)
                            secs = pm.design_band_polished(t, fc, gain, q, si, fs)
                            head = [num(fs, where), t, '%d' % si, num(fc, where), num(q, where),
                                    num(gain, where)]
                            for i, s in enumerate(secs):
                                cells = head + ['%d' % i, s['cls'],
                                                '1' if s['hasSvf'] else '0',
                                                '1' if s['hasOnePole'] else '0']
                                for key in SVF_KEYS:
                                    cells.append(num(s[key], where) if s['hasSvf'] else '-')
                                for key in OP_KEYS:
                                    cells.append(num(s[key], where) if s['hasOnePole'] else '-')
                                cells.append(num(s['weight'], where))
                                w('\t'.join(cells) + '\n')
                                rows += 1
    out.flush()
    sys.stderr.write('dump_polish: %d rows\n' % rows)


if __name__ == '__main__':
    main()
