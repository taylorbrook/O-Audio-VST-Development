#!/usr/bin/env python3
"""O-GranulatorInstrument: the factory-source table generator.

Resources/factory/manifest.json is the source of truth. From it this script
writes four files:

  Source/dsp/GiFactoryTable.inc              pins, count and table cases (included by GiFactory.h)
  Resources/factory/sources.cmake            the juce_add_binary_data file list
  tests/golden/factory-sources.sha256        sha256 of every .flac, table order
  tests/render-harness/factory_specs.inc     the harness's expectation per source (FSP1 and the 1.2.0 rows)

  factory_table.py                 write the four files
  factory_table.py --check         exit 1 when a file on disk differs from what the manifest
                                   and the .flac bytes generate, when a .flac header disagrees
                                   with the manifest (48 kHz, channels, frames), or a pin is missing
  factory_table.py --apply-pins F  merge the JSON lines printed by the render harness
                                   (--pin-factory <dir>) into the manifest, then write

Standard library only. Run from anywhere.
"""
import hashlib, json, os, sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
MANIFEST = "Resources/factory/manifest.json"
OUT_TABLE = "Source/dsp/GiFactoryTable.inc"
OUT_CMAKE = "Resources/factory/sources.cmake"
OUT_SHA = "tests/golden/factory-sources.sha256"
OUT_SPECS = "tests/render-harness/factory_specs.inc"
HEAD = "GENERATED by tools/factory_table.py from Resources/factory/manifest.json. Do not edit."
OLD8 = ["harmonic", "pluck", "bell", "vowel", "noise_bed", "dust", "drone", "pulse"]


def camel(i):
    return "".join(w[:1].upper() + w[1:] for w in i.split("_"))


def flac_path(s):
    return "Resources/factory/%s.flac" % s["id"]


def streaminfo(path):
    """(rate, channels, bits, frames) from the FLAC STREAMINFO block."""
    with open(path, "rb") as f:
        b = f.read(42)
    if b[:4] != b"fLaC" or (b[4] & 0x7F) != 0:
        raise ValueError("%s: not a FLAC file with a leading STREAMINFO block" % path)
    v = int.from_bytes(b[18:26], "big")
    return v >> 44, ((v >> 41) & 7) + 1, ((v >> 36) & 31) + 1, v & ((1 << 36) - 1)


def validate(m):
    errs = []
    src = m["sources"]
    ids = [s["id"] for s in src]
    if ids[:8] != OLD8:
        errs.append("entries 0-7 must be the 1.0.0 set in its order: %s" % OLD8)
    if len(set(ids)) != len(ids):
        errs.append("duplicate id")
    for s in src:
        i = s["id"]
        if not i or any(not (c.islower() or c.isdigit() or c == "_") for c in i):
            errs.append("%s: ids are [a-z0-9_] only" % i)
        if s["category"] not in m["categories"]:
            errs.append("%s: unknown category %s" % (i, s["category"]))
        if not (0 <= int(s["root_note"]) <= 127) or not (-100.0 <= float(s["root_cents"]) <= 100.0):
            errs.append("%s: root out of range" % i)
        if not s["name"] or '"' in s["name"] or "\\" in s["name"]:
            errs.append("%s: bad name" % i)
        if s["kind"] not in ("synthetic", "sample"):
            errs.append("%s: kind" % i)
    return errs


def pin(s, key):
    v = s.get(key)
    return "0x%016xull" % int(v, 16) if v else "0ull"


def gen(m):
    src = m["sources"]
    out = {}

    t = ["// %s" % HEAD, "// %d sources. Entries 0-7 are the 1.0.0 set and never move." % len(src), ""]
    t.append("#if defined (OGI_FACTORY_TABLE_PINS)")
    w = max(len(camel(s["id"])) for s in src)
    for s in src:
        c = camel(s["id"])
        t.append("    inline constexpr std::uint64_t kHash%s = %s, kFull%s = %s;"
                 % (c.ljust(w), pin(s, "kHash"), c.ljust(w), pin(s, "kFull")))
    t.append("    inline constexpr int kCuratedFactoryCount = %d;" % len(src))
    t.append("#elif defined (OGI_FACTORY_TABLE_CASES)")
    for k, s in enumerate(src):
        i, c = s["id"], camel(s["id"])
        t.append('            case %d: return { "%s", "%s", "%s", %d, %sf, D::%s_flac, (std::size_t) D::%s_flacSize, kHash%s, kFull%s };'
                 % (k, i, s["name"], s["category"], int(s["root_note"]), repr(float(s["root_cents"])), i, i, c, c))
    t.append("#else")
    t.append(" #error \"define OGI_FACTORY_TABLE_PINS or OGI_FACTORY_TABLE_CASES before including GiFactoryTable.inc\"")
    t.append("#endif")
    out[OUT_TABLE] = "\n".join(t) + "\n"

    c = ["# %s" % HEAD, "set(OGI_FACTORY_SOURCE_FILES"]
    c += ["    %s" % flac_path(s) for s in src]
    c.append(")")
    out[OUT_CMAKE] = "\n".join(c) + "\n"

    sha = []
    for s in src:
        with open(os.path.join(ROOT, flac_path(s)), "rb") as f:
            sha.append("%s  %s" % (hashlib.sha256(f.read()).hexdigest(), flac_path(s)))
    out[OUT_SHA] = "\n".join(sha) + "\n"

    sp = ["// %s" % HEAD,
          "// { id, name, category, channels, frames, rootNote, rootCents, seam, synthetic, refPartial }"]
    for s in src:
        sp.append('    { "%s", "%s", "%s", %d, %d, %d, %s, %s, %s, %d },'
                  % (s["id"], s["name"], s["category"], s["channels"], s["frames"], int(s["root_note"]),
                     repr(float(s["root_cents"])), "true" if s.get("seam") else "false",
                     "true" if s["kind"] == "synthetic" else "false", int(s.get("ref_partial", 0))))
    out[OUT_SPECS] = "\n".join(sp) + "\n"
    return out


def main():
    args = sys.argv[1:]
    with open(os.path.join(ROOT, MANIFEST)) as f:
        m = json.load(f)

    if args[:1] == ["--apply-pins"]:
        pins = {}
        with open(args[1]) as f:
            for line in f:
                line = line.strip()
                if line.startswith("{"):
                    p = json.loads(line)
                    pins[p["id"]] = p
        n = 0
        for s in m["sources"]:
            p = pins.get(s["id"])
            if p is None:
                continue
            if s["id"] in OLD8:
                if (int(s["kHash"], 16), int(s["kFull"], 16)) != (int(p["kHash"], 16), int(p["kFull"], 16)):
                    sys.exit("REFUSED: %s is one of the 1.0.0 set and its pins differ" % s["id"])
                continue
            for k in ("kHash", "kFull", "channels", "frames"):
                s[k] = p[k]
            n += 1
        with open(os.path.join(ROOT, MANIFEST), "w") as f:
            json.dump(m, f, indent=1)
            f.write("\n")
        print("pins applied to %d sources" % n)
        args = []

    errs = validate(m)
    for s in m["sources"]:
        p = os.path.join(ROOT, flac_path(s))
        if not os.path.exists(p):
            errs.append("%s: %s missing" % (s["id"], flac_path(s)))
            continue
        rate, ch, bits, frames = streaminfo(p)
        if (rate, ch, frames) != (48000, s["channels"], s["frames"]):
            errs.append("%s: file is %d Hz / %d ch / %d frames, manifest says 48000 / %d / %d"
                        % (s["id"], rate, ch, frames, s["channels"], s["frames"]))
    if errs:
        for e in errs:
            print("ERROR", e)
        sys.exit(1)

    out = gen(m)
    if args[:1] == ["--check"]:
        bad = 0
        for s in m["sources"]:
            if not s.get("kHash") or not s.get("kFull"):
                print("DRIFT %s: pin missing" % s["id"])
                bad += 1
        for rel, text in out.items():
            p = os.path.join(ROOT, rel)
            cur = open(p, newline="").read() if os.path.exists(p) else None
            if cur != text:
                print("DRIFT %s" % rel)
                bad += 1
        total = sum(os.path.getsize(os.path.join(ROOT, flac_path(s))) for s in m["sources"])
        print("factory_table --check: %d sources, %d B embedded, %s" % (len(m["sources"]), total, "OK" if bad == 0 else "%d DRIFT" % bad))
        sys.exit(1 if bad else 0)

    for rel, text in out.items():
        with open(os.path.join(ROOT, rel), "w", newline="\n") as f:
            f.write(text)
        print("wrote", rel)


if __name__ == "__main__":
    main()
