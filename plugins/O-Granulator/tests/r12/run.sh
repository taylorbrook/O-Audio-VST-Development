#!/usr/bin/env bash
# ==============================================================================
#   O-Granulator — R12 2.1-equivalence out-of-tree null (PLAN-2.2 T16,
#   RESEARCH-2.2 §7). Exit 0 = both cases max|Δ| == 0.
#
#   usage: plugins/O-Granulator/tests/r12/run.sh [WORK_DIR]
#          (WORK_DIR default: ${TMPDIR:-/tmp}/ogran-r12; nothing is written
#           inside the repo)
#
#   How it works
#   ------------
#   1. OLD tree: `git archive 6508c635 plugins/O-Granulator modules` (the
#      verified 2.1 tree and ITS modules) → WORK_DIR/old/. grain-engine,
#      pitch-collections and `scripts/param-dump/` must be byte-identical
#      between 6508c635 and HEAD (the script checks with `git diff --quiet`);
#      every other module (reverb-unit 1.2.0, PLAN-2.4 T10) comes from the
#      archive on the old side, the working tree on the new side.
#      The gitignored Source/ui/public/modules/*.js copies are regenerated by
#      ouaricon_add_module at configure (and only the editor embeds UI files —
#      the console never compiles them).
#   2. NEW tree: the working tree's plugins/O-Granulator (uncommitted edits
#      included — that is what is being proved).
#   3. One tiny CMake wrapper project per side (WORK_DIR/proj-{old,new}): it
#      sets the Ouaricon branding vars, adds JUCE, symlinks `modules` and
#      `scripts` (the plugin CMakeLists resolves them via CMAKE_SOURCE_DIR),
#      add_subdirectory()s the plugin tree, then calls the SAME
#      ouaricon_add_processor_console() the render harness uses, with THIS
#      directory's r12_render.cpp as the driver (identical source both sides)
#      and OGRAN_TEST_HOOKS=1 (diag counters only; every hook stays off).
#      Release, Ninja, cxx_std_20 — the build/ settings.
#   4. Each binary renders the cases (free: N 100 @ cap 128; capped: N 400 @
#      cap 32); `r12_render compare` reports max|Δ| and the bitwise diff count.
#      PASS = max|Δ| == 0 (and a live, non-silent render; capped must kill).
# ==============================================================================
set -euo pipefail

OLD_SHA=6508c635
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(cd "$HERE/../../../.." && pwd)"
WORK="${1:-${TMPDIR:-/tmp}/ogran-r12}"
JUCE_SRC="${JUCE_DIR:-/Users/taylorbrook/JUCE}"
mkdir -p "$WORK"

cd "$REPO"
# The engine's own modules must be byte-identical to the old tree. Every other
# module (reverb-unit 1.2.0 from 2.4 T10 on) is taken from the OLD tree's
# archive for the old side, so the old side builds exactly what it shipped.
if ! git diff --quiet "${OLD_SHA}" -- modules/synthesis/grain-engine modules/tuning/pitch-collections scripts/param-dump; then
    echo "R12: grain-engine / pitch-collections / scripts/param-dump differ from ${OLD_SHA} — archive them too before trusting a null" >&2
    exit 2
fi

# 1. Old tree (re-extracted every run: never trust a stale copy).
rm -rf "$WORK/old"
mkdir -p "$WORK/old"
git archive "${OLD_SHA}" plugins/O-Granulator modules | tar -x -C "$WORK/old"

make_proj () {   # $1 = side, $2 = plugin tree, $3 = modules tree
    local P="$WORK/proj-$1"
    mkdir -p "$P"
    ln -sfn "$3" "$P/modules"
    ln -sfn "$REPO/scripts" "$P/scripts"
    cat > "$P/CMakeLists.txt" <<EOF
cmake_minimum_required(VERSION 3.22)
project(ogran_r12_$1 VERSION 1.0.0)
set(OUARICON_COMPANY_NAME "Ouaricon Audio Development")
set(OUARICON_MANUFACTURER_CODE OuDv)
set(OUARICON_DEV_SUFFIX "-dev")
add_subdirectory("${JUCE_SRC}" JUCE)
add_subdirectory("$2" gran)
include(\${CMAKE_SOURCE_DIR}/scripts/param-dump/ParamDump.cmake)
ouaricon_add_processor_console(OuariconGranulator "$2/Source" "${HERE}/r12_render.cpp" r12)
target_compile_features(proj-$1-r12 PRIVATE cxx_std_20)
target_compile_definitions(proj-$1-r12 PRIVATE OGRAN_TEST_HOOKS=1)
EOF
    if [ ! -f "$P/build/build.ninja" ]; then
        cmake -S "$P" -B "$P/build" -G Ninja -DCMAKE_BUILD_TYPE=Release > "$P/configure.log"
    fi
    ninja -C "$P/build" "proj-$1-r12" > "$P/build.log" 2>&1 || { tail -40 "$P/build.log"; exit 3; }
}

make_proj old "$WORK/old/plugins/O-Granulator" "$WORK/old/modules"
make_proj new "$REPO/plugins/O-Granulator" "$REPO/modules"

bin () { echo "$WORK/proj-$1/build/proj-$1-r12_artefacts/Release/proj-$1-r12"; }

status=0
cd "$WORK"
field () { echo "$1" | sed -n "s/.* $2 \([0-9-]*\).*/\1/p"; }
for c in free capped; do
    echo "== R12 case $c"
    o="$("$(bin old)" "old-$c.f32" "$c" 2>/dev/null)"; echo "  old $o"
    n="$("$(bin new)" "new-$c.f32" "$c" 2>/dev/null)"; echo "  new $n"
    # Non-vacuity: free must be steal- and kill-free on BOTH sides, capped must kill.
    live=1
    for d in "$o" "$n"; do
        if [ "$c" = free ]; then
            [ "$(field "$d" steals)" = 0 ] && [ "$(field "$d" kills)" = 0 ] || live=0
        else
            [ "$(field "$d" kills)" -gt 0 ] || live=0
        fi
    done
    if "$(bin new)" compare "old-$c.f32" "new-$c.f32" && [ $live = 1 ]; then
        echo "  [PASS] R12 $c: max|d| == 0"
    else
        [ $live = 1 ] || echo "  VACUOUS (steal/kill precondition not met)"
        echo "  [FAIL] R12 $c"; status=1
    fi
done
exit $status
